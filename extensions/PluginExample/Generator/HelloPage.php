<?php

namespace PluginExample\Generator;

use Cecil\Collection\Page\Page;
use Cecil\Collection\Page\Type;
use Cecil\Generator\AbstractGenerator;

/**
 * Generates a page without Markdown file, listing the sections of the site.
 */
class HelloPage extends AbstractGenerator
{
    public function generate(): void
    {
        $path = (string) $this->config->get('plugin_example.hello.path');
        if ($path === '') {
            return;
        }

        $sections = [];
        foreach ($this->builder->getPages()->filter(fn (Page $page) => $page->getType() === Type::SECTION->value) as $section) {
            $sections[] = \sprintf('<li><a href="/%s/">%s</a></li>', $section->getPath(), htmlspecialchars((string) $section->getVariable('title')));
        }

        $page = (new Page('plugin-example-hello'))
            ->setType(Type::PAGE)
            ->setPath($path)
            ->setBodyHtml(\sprintf('<p>This page is generated by the plugin example.</p><ul>%s</ul>', implode('', $sections)))
            ->setVariable('title', (string) $this->config->get('plugin_example.hello.title'))
            ->setVariable('date', new \DateTime());
        $this->generatedPages->add($page);
    }
}
